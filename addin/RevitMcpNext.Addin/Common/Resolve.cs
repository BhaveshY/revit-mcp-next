        /// <summary>id | name | "solid" (the solid fill found by IsSolidFill), optionally limited to a target (Drafting/Model).</summary>
        public static FillPatternElement FillPattern(Document doc, string value, string param = "pattern", FillPatternTarget? target = null)
        {
            string text = (value ?? string.Empty).Trim();
            List<FillPatternElement> patterns = new FilteredElementCollector(doc).OfClass(typeof(FillPatternElement)).Cast<FillPatternElement>()
                .Where(p => !target.HasValue || SafePattern(p)?.Target == target.Value).ToList();
            if (text.Length == 0 || text.Equals("solid", StringComparison.OrdinalIgnoreCase) || text.Equals("solid fill", StringComparison.OrdinalIgnoreCase))
            {
                FillPatternElement solid = patterns.FirstOrDefault(p => SafePattern(p)?.IsSolidFill == true);
                if (solid != null) return solid;
            }
            FillPatternElement byId = ById<FillPatternElement>(doc, text);
            if (byId != null) return byId;
            return Single(patterns, p => p.Name, text, param, "fill pattern");
        }

        /// <summary>id | name | "solid" (the solid line pattern).</summary>
        public static ElementId LinePatternId(Document doc, string value, string param = "line_pattern")
        {
            string text = (value ?? string.Empty).Trim();
            if (text.Equals("solid", StringComparison.OrdinalIgnoreCase)) return LinePatternElement.GetSolidPatternId();
            LinePatternElement byId = ById<LinePatternElement>(doc, text);
            if (byId != null) return byId.Id;
            List<LinePatternElement> patterns = new FilteredElementCollector(doc).OfClass(typeof(LinePatternElement)).Cast<LinePatternElement>().ToList();
            return Single(patterns, p => p.Name, text, param, "line pattern").Id;
        }

        /// <summary>A line style (subcategory of Lines) by id or name.</summary>
        public static GraphicsStyle LineStyle(Document doc, string value, string param = "line_style")
        {
            string text = (value ?? string.Empty).Trim();
            GraphicsStyle byId = ById<GraphicsStyle>(doc, text);
            if (byId != null) return byId;
            Category lines = Autodesk.Revit.DB.Category.GetCategory(doc, BuiltInCategory.OST_Lines);
            var styles = new List<GraphicsStyle>();
            if (lines != null)
            {
                foreach (Category sub in lines.SubCategories)
                {
                    GraphicsStyle style = sub.GetGraphicsStyle(GraphicsStyleType.Projection);
                    if (style != null) styles.Add(style);
                }
            }
            return Single(styles, s => s.GraphicsStyleCategory?.Name ?? s.Name, text, param, "line style");
        }

