        /// <summary>
        /// Elements named by <paramref name="key"/>: numeric ids, UniqueIds, or "selection" (the registry's last UI
        /// selection of the doc; a stale selection adds notice SELECTION_STALE). Ids that no longer exist are skipped
        /// with warn IDS_GONE; when none remain, NOT_FOUND.
        /// </summary>
        public static List<Element> Elements(Document doc, PayloadReader args, string key, RequestContext ctx = null)
        {
            var tokens = new List<string>();
            List<long> ids = args.IdValues(key, tokens);
            var result = new List<Element>();
            var gone = new List<long>();
            var seen = new HashSet<long>();
            foreach (long id in ids)
            {
                Element element = SafeGet(doc, new ElementId(id));
                if (element == null) gone.Add(id);
                else if (seen.Add(element.Id.Value)) result.Add(element);
            }
            foreach (string token in tokens)
            {
                if (token.Equals("selection", StringComparison.OrdinalIgnoreCase))
                {
                    SelectionState selection = (ctx?.Registry ?? McpRuntime.Registry)?.GetSelection(doc) ?? new SelectionState();
                    if (!selection.IsActiveDoc && selection.AtUtc.HasValue)
                    {
                        ctx?.Notice(NoticeCodes.SelectionStale, "selection of '" + doc.Title + "' as of " + selection.AtUtc.Value.ToString("HH:mm:ss", CultureInfo.InvariantCulture) + " UTC (not the active document)");
                    }
                    foreach (long id in selection.Ids)
                    {
                        Element element = SafeGet(doc, new ElementId(id));
                        if (element != null && seen.Add(element.Id.Value)) result.Add(element);
                    }
                    continue;
                }
                Element byUnique = null;
                try { byUnique = doc.GetElement(token); } catch { }
                if (byUnique != null)
                {
                    if (seen.Add(byUnique.Id.Value)) result.Add(byUnique);
                }
                else
                {
                    throw OpException.NotFound(args.Field(key), "element", token, new string[0]);
                }
            }
            if (gone.Count > 0)
            {
                ctx?.Warn(WarningCodes.IdsGone, gone.Count.ToString(CultureInfo.InvariantCulture) + " id(s) no longer exist and were skipped", gone.Take(20));
            }
            if (result.Count == 0 && (ids.Count > 0 || tokens.Count > 0))
            {
                throw new OpException(ErrorCodes.NotFound, "None of the elements in " + args.Field(key) + " exist in '" + doc.Title + "'.",
                    Details(args.Field(key), "element", string.Join(",", ids.Take(10)), new string[0]));
            }
            return result;
        }

        public static Element SafeGet(Document doc, ElementId id)
        {
            try
            {
                return id == null || id == ElementId.InvalidElementId ? null : doc.GetElement(id);
            }
            catch
            {
                return null;
            }
        }

        /// <summary>The element with this numeric id when it is a T, else null (non-numeric text returns null).</summary>
        public static T ById<T>(Document doc, string value) where T : Element
        {
            long? id = Wire.ToLong(value?.Trim());
            if (!id.HasValue || doc == null) return null;
            return SafeGet(doc, new ElementId(id.Value)) as T;
        }

