            if (byId != null) return byId;
            List<DesignOption> options = new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.DesignOption)).Cast<DesignOption>().ToList();
            return Single(options, o => o.Name, value, param, "design option");
        }

        /// <summary>A Revit link instance by id, instance name, type name or file name.</summary>
        public static RevitLinkInstance Link(Document doc, string value, string param = "link")
        {
            string text = (value ?? string.Empty).Trim();
            RevitLinkInstance byId = ById<RevitLinkInstance>(doc, text);
            if (byId != null) return byId;
            List<RevitLinkInstance> links = new FilteredElementCollector(doc).OfClass(typeof(RevitLinkInstance)).Cast<RevitLinkInstance>().ToList();
            List<RevitLinkInstance> matches = links.Where(l =>
                Eq(l.Name, text) || Eq(doc.GetElement(l.GetTypeId())?.Name, text) ||
                Eq(Path.GetFileNameWithoutExtension(doc.GetElement(l.GetTypeId())?.Name ?? string.Empty), Path.GetFileNameWithoutExtension(text)) ||
                (l.Name ?? string.Empty).StartsWith(text + " :", StringComparison.OrdinalIgnoreCase)).ToList();
            if (matches.Count == 1) return matches[0];
            if (matches.Count > 1) throw OpException.Ambiguous(param, "link", value, matches.Select(l => l.Name));
            throw OpException.NotFound(param, "link", value, Closest(text, links.Select(l => l.Name)));
        }

