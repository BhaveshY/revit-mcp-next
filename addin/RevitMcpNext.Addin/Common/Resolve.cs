    /// <summary>
    /// English names for built-in categories and parameters (SPEC §9.7), from the embedded
    /// Common/Aliases/aliases-&lt;year&gt;.json ({categories:{label:"OST_x"}, parameters:{label:["BIP",...]}}). The seed is
    /// hand-written (W1); P-READ replaces the files with tables generated by dev.dump_labels under /language ENU.
    /// </summary>
    internal static class EnglishAliases
    {
        private static readonly object Gate = new object();
        private static Dictionary<string, BuiltInCategory> _categoryByLabel;
        private static Dictionary<BuiltInCategory, string> _labelByCategory;
        private static Dictionary<string, List<BuiltInParameter>> _parametersByLabel;
        private static Dictionary<BuiltInParameter, string> _labelByParameter;

        /// <summary>English label → category (case-insensitive).</summary>
        public static bool TryCategory(string label, out BuiltInCategory category)
        {
            EnsureLoaded();
            category = BuiltInCategory.INVALID;
            if (string.IsNullOrWhiteSpace(label)) return false;
            return _categoryByLabel.TryGetValue(label.Trim(), out category);
        }

        /// <summary>The English label of a category, or null when the table has none.</summary>
        public static string LabelOf(BuiltInCategory category)
        {
            EnsureLoaded();
            return _labelByCategory.TryGetValue(category, out string label) ? label : null;
        }

        /// <summary>Built-in parameters carrying this English label (several for e.g. "Width"); empty when unknown.</summary>
        public static IReadOnlyList<BuiltInParameter> Parameters(string label)
        {
            EnsureLoaded();
            if (string.IsNullOrWhiteSpace(label)) return new List<BuiltInParameter>();
            return _parametersByLabel.TryGetValue(label.Trim(), out List<BuiltInParameter> list) ? list : new List<BuiltInParameter>();
        }

        /// <summary>The English label of a built-in parameter, or null.</summary>
        public static string LabelOf(BuiltInParameter parameter)
        {
            EnsureLoaded();
            return _labelByParameter.TryGetValue(parameter, out string label) ? label : null;
        }

        public static IEnumerable<string> CategoryLabels()
        {
            EnsureLoaded();
            return _categoryByLabel.Keys;
        }

        private static void EnsureLoaded()
        {
            if (_categoryByLabel != null) return;
            lock (Gate)
            {
                if (_categoryByLabel != null) return;
                var categoryByLabel = new Dictionary<string, BuiltInCategory>(StringComparer.OrdinalIgnoreCase);
                var labelByCategory = new Dictionary<BuiltInCategory, string>();
                var parametersByLabel = new Dictionary<string, List<BuiltInParameter>>(StringComparer.OrdinalIgnoreCase);
                var labelByParameter = new Dictionary<BuiltInParameter, string>();
                int year = McpRuntime.Instance?.Year ?? 2024;
                foreach (string name in new[] { "aliases-" + year.ToString(CultureInfo.InvariantCulture) + ".json", "aliases-2024.json", "aliases-2027.json" }.Distinct())
                {
                    try
                    {
                        string json = ReadResource("RevitMcpNext.Aliases." + name);
                        if (json == null) continue;
                        var root = JsonWireCodec.DeserializeObject(json) as IDictionary<string, object>;
                        if (root == null) continue;
                        foreach (KeyValuePair<string, object> pair in Wire.AsMap(Wire.Get(root, "categories")) ?? new Dictionary<string, object>())
                        {
                            string token = Convert.ToString(pair.Value, CultureInfo.InvariantCulture);
                            if (!Enum.TryParse(token, true, out BuiltInCategory category)) continue;
                            if (!categoryByLabel.ContainsKey(pair.Key)) categoryByLabel[pair.Key] = category;
                            if (!labelByCategory.ContainsKey(category)) labelByCategory[category] = pair.Key;
                        }
                        foreach (KeyValuePair<string, object> pair in Wire.AsMap(Wire.Get(root, "parameters")) ?? new Dictionary<string, object>())
                        {
                            IList<object> tokens = Wire.AsList(pair.Value) ?? new List<object> { pair.Value };
                            if (!parametersByLabel.TryGetValue(pair.Key, out List<BuiltInParameter> list))
                            {
                                list = new List<BuiltInParameter>();
                                parametersByLabel[pair.Key] = list;
                            }
                            foreach (object tokenValue in tokens)
                            {
                                string token = Convert.ToString(tokenValue, CultureInfo.InvariantCulture);
                                if (!Enum.TryParse(token, true, out BuiltInParameter parameter)) continue;
                                if (!list.Contains(parameter)) list.Add(parameter);
                                if (!labelByParameter.ContainsKey(parameter)) labelByParameter[parameter] = pair.Key;
                            }
                        }
                    }
                    catch (Exception ex)
                    {
                        DiagnosticsLogger.Warn("aliases", "Could not load " + name + ": " + ex.Message);
                    }
                }
                _labelByCategory = labelByCategory;
                _parametersByLabel = parametersByLabel;
                _labelByParameter = labelByParameter;
                _categoryByLabel = categoryByLabel;
            }
        }

        private static string ReadResource(string name)
        {
            using (Stream stream = typeof(EnglishAliases).Assembly.GetManifestResourceStream(name))
            {
                if (stream == null) return null;
                using (var reader = new StreamReader(stream)) return reader.ReadToEnd();
            }
        }
    }

    /// <summary>
    /// Name/id resolution shared by all handlers (SPEC §9.5). Every miss throws NOT_FOUND (or AMBIGUOUS_NAME) with
    /// details {param, kind, value, candidates[]}, closest names first. Names compare case-insensitively.
    /// </summary>
    internal static class Resolve
    {
        // ---------------------------------------------------------------------------------------------------------
        // Categories
        // ---------------------------------------------------------------------------------------------------------

        /// <summary>
        /// English label (exact, then case-insensitive, then singular/plural), localized name (doc.Settings.Categories),
        /// then OST_ token or enum name.
        /// </summary>
        public static bool TryCategory(Document doc, string value, out BuiltInCategory category)
        {
            category = BuiltInCategory.INVALID;
            if (string.IsNullOrWhiteSpace(value)) return false;
            string text = value.Trim();
            if (EnglishAliases.TryCategory(text, out category)) return true;
            if (EnglishAliases.TryCategory(Plural(text), out category)) return true;
            if (text.EndsWith("s", StringComparison.OrdinalIgnoreCase) && EnglishAliases.TryCategory(text.Substring(0, text.Length - 1), out category)) return true;

            if (doc != null)
            {
                foreach (Category candidate in LocalizedCategories(doc))
                {
                    if (string.Equals(candidate.Name, text, StringComparison.OrdinalIgnoreCase))
                    {
                        category = SafeBuiltIn(candidate);
                        if (category != BuiltInCategory.INVALID) return true;
                    }
                }
            }

            string token = text.Replace(" ", string.Empty);
            if (Enum.TryParse(token, true, out category) && category != BuiltInCategory.INVALID && Enum.IsDefined(typeof(BuiltInCategory), category)) return true;
            if (Enum.TryParse("OST_" + token, true, out category) && Enum.IsDefined(typeof(BuiltInCategory), category)) return true;
            long? id = Wire.ToLong(text);
            if (id.HasValue && id.Value < 0 && Enum.IsDefined(typeof(BuiltInCategory), (int)id.Value))
            {
                category = (BuiltInCategory)(int)id.Value;
                return true;
            }
            category = BuiltInCategory.INVALID;
            return false;
        }

        public static BuiltInCategory CategoryId(Document doc, string value, string param = "category")
        {
            if (TryCategory(doc, value, out BuiltInCategory category)) return category;
            IEnumerable<string> names = EnglishAliases.CategoryLabels().Concat(LocalizedCategories(doc).Select(c => c.Name));
            throw OpException.NotFound(param, "category", value, Closest(value, names));
        }

        public static Category Category(Document doc, string value, string param = "category")
        {
            BuiltInCategory id = CategoryId(doc, value, param);
            Category category = null;
            try { category = Autodesk.Revit.DB.Category.GetCategory(doc, id); } catch { }
            if (category == null) throw OpException.NotFound(param, "category", value, new string[0]);
            return category;
        }

        public static List<BuiltInCategory> Categories(Document doc, IEnumerable<string> values, string param = "category")
        {
            return (values ?? Enumerable.Empty<string>()).Select(v => CategoryId(doc, v, param)).Distinct().ToList();
        }

