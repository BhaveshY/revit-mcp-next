        /// <summary>id | "Family: Type" | "Type" (unique). <paramref name="category"/> narrows the candidates.</summary>
        public static T Type<T>(Document doc, string value, string param, BuiltInCategory? category = null) where T : ElementType
        {
            string text = (value ?? string.Empty).Trim();
            T byId = ById<T>(doc, text);
            if (byId != null) return byId;

            var collector = new FilteredElementCollector(doc).OfClass(typeof(T));
            if (category.HasValue) collector = collector.OfCategory(category.Value);
            List<T> types = collector.Cast<T>().ToList();
            if (typeof(T) == typeof(ElementType) || types.Count == 0)
            {
                var all = new FilteredElementCollector(doc).WhereElementIsElementType();
                if (category.HasValue) all = all.OfCategory(category.Value);
                types = all.OfType<T>().ToList();
            }

            int colon = text.IndexOf(':');
            if (colon > 0)
            {
                string family = text.Substring(0, colon).Trim();
                string typeName = text.Substring(colon + 1).Trim();
                List<T> exact = types.Where(t => Eq(t.FamilyName, family) && Eq(t.Name, typeName)).ToList();
                if (exact.Count == 1) return exact[0];
                if (exact.Count > 1) return exact[0];
            }

            List<T> byName = types.Where(t => Eq(t.Name, text)).ToList();
            if (byName.Count == 1) return byName[0];
            if (byName.Count > 1) throw OpException.Ambiguous(param, "type", value, byName.Select(FullTypeName));
            throw OpException.NotFound(param, "type", value, Closest(text, types.Select(FullTypeName)));
        }

        /// <summary>The document's default type for a category (or the first type of that category).</summary>
        public static T DefaultType<T>(Document doc, BuiltInCategory category) where T : ElementType
        {
            try
            {
                ElementTypeGroup? group = DefaultGroupOf(category);
                if (group.HasValue)
                {
                    ElementId id = doc.GetDefaultElementTypeId(group.Value);
                    if (id != null && id != ElementId.InvalidElementId && doc.GetElement(id) is T typed) return typed;
                }
                ElementId familyDefault = doc.GetDefaultFamilyTypeId(new ElementId(category));
                if (familyDefault != null && familyDefault != ElementId.InvalidElementId && doc.GetElement(familyDefault) is T familyTyped) return familyTyped;
            }
            catch
            {
                // Fall back to the first type.
            }
            return new FilteredElementCollector(doc).OfCategory(category).WhereElementIsElementType().OfType<T>().FirstOrDefault();
        }

        public static string FullTypeName(ElementType type)
        {
            if (type == null) return string.Empty;
            string family = type.FamilyName;
            return string.IsNullOrWhiteSpace(family) ? type.Name : family + ": " + type.Name;
        }

