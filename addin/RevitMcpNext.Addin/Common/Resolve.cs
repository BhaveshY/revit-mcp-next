        public static Workset Workset(Document doc, string value, string param = "workset")
        {
            if (!doc.IsWorkshared) throw new OpException(ErrorCodes.NotFound, "'" + doc.Title + "' is not workshared, so it has no worksets.", Details(param, "workset", value, new string[0]));
            List<Workset> worksets = new FilteredWorksetCollector(doc).OfKind(WorksetKind.UserWorkset).ToList();
            long? id = Wire.ToLong(value);
            if (id.HasValue)
            {
                Workset byId = worksets.FirstOrDefault(w => w.Id.IntegerValue == id.Value);
                if (byId != null) return byId;
            }
            return Single(worksets, w => w.Name, value, param, "workset");
        }

