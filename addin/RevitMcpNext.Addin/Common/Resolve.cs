        /// <summary>Exactly one item named <paramref name="value"/> (case-insensitive), else NOT_FOUND/AMBIGUOUS_NAME.</summary>
        public static T Single<T>(IEnumerable<T> items, Func<T, string> name, string value, string param, string kind, Func<T, string> describe = null)
        {
            List<T> list = items.ToList();
            string text = (value ?? string.Empty).Trim();
            List<T> exact = list.Where(item => string.Equals(name(item), text, StringComparison.Ordinal)).ToList();
            if (exact.Count == 1) return exact[0];
            List<T> matches = exact.Count > 1 ? exact : list.Where(item => Eq(name(item), text)).ToList();
            if (matches.Count == 1) return matches[0];
            Func<T, string> label = describe ?? name;
            if (matches.Count > 1) throw OpException.Ambiguous(param, kind, value, matches.Select(label));
            throw OpException.NotFound(param, kind, value, Closest(text, list.Select(label)));
        }

        /// <summary>Up to <paramref name="max"/> names closest to <paramref name="value"/> (prefix/contains first, then edit distance).</summary>
        public static List<string> Closest(string value, IEnumerable<string> names, int max = 8)
        {
            string text = (value ?? string.Empty).Trim();
            return (names ?? Enumerable.Empty<string>())
                .Where(n => !string.IsNullOrWhiteSpace(n))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(n => n.StartsWith(text, StringComparison.OrdinalIgnoreCase) ? 0 : n.IndexOf(text, StringComparison.OrdinalIgnoreCase) >= 0 ? 1 : 2)
                .ThenBy(n => ControlOperations.Levenshtein(n, text))
                .Take(max)
                .ToList();
        }

        public static bool Eq(string left, string right)
        {
            return string.Equals((left ?? string.Empty).Trim(), (right ?? string.Empty).Trim(), StringComparison.OrdinalIgnoreCase);
        }

        private static Dictionary<string, object> Details(string param, string kind, string value, IEnumerable<string> candidates)
        {
            return new Dictionary<string, object>
            {
                ["param"] = param,
                ["kind"] = kind,
                ["value"] = value,
                ["candidates"] = (candidates ?? Enumerable.Empty<string>()).ToList()
            };
        }

        private static IEnumerable<string> LevelNames(Document doc)
        {
            return new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.Level)).Cast<Level>().Select(l => l.Name);
        }

        private static IEnumerable<Category> LocalizedCategories(Document doc)
        {
            if (doc == null) yield break;
            Categories categories;
            try { categories = doc.Settings.Categories; } catch { yield break; }
            foreach (Category category in categories) yield return category;
        }

        internal static BuiltInCategory SafeBuiltIn(Category category)
        {
            try
            {
                return category == null ? BuiltInCategory.INVALID : category.BuiltInCategory;
            }
            catch
            {
                return BuiltInCategory.INVALID;
            }
        }

        private static FillPattern SafePattern(FillPatternElement element)
        {
            try { return element?.GetFillPattern(); } catch { return null; }
        }

        private static View SafeActiveView(Document doc)
        {
            try { return doc?.ActiveView; } catch { return null; }
        }

        private static string Plural(string text)
        {
            if (text.EndsWith("y", StringComparison.OrdinalIgnoreCase)) return text.Substring(0, text.Length - 1) + "ies";
            return text.EndsWith("s", StringComparison.OrdinalIgnoreCase) ? text : text + "s";
        }

        private static ElementTypeGroup? DefaultGroupOf(BuiltInCategory category)
        {
            switch (category)
            {
                case BuiltInCategory.OST_Walls: return ElementTypeGroup.WallType;
                case BuiltInCategory.OST_Floors: return ElementTypeGroup.FloorType;
                case BuiltInCategory.OST_Roofs: return ElementTypeGroup.RoofType;
                case BuiltInCategory.OST_Ceilings: return ElementTypeGroup.CeilingType;
                case BuiltInCategory.OST_Grids: return ElementTypeGroup.GridType;
                case BuiltInCategory.OST_Levels: return ElementTypeGroup.LevelType;
                case BuiltInCategory.OST_Stairs: return ElementTypeGroup.StairsType;
                case BuiltInCategory.OST_StairsRailing: return ElementTypeGroup.StairsRailingType;
                case BuiltInCategory.OST_TextNotes: return ElementTypeGroup.TextNoteType;
                case BuiltInCategory.OST_Dimensions: return ElementTypeGroup.LinearDimensionType;
                case BuiltInCategory.OST_PipeCurves: return ElementTypeGroup.PipeType;
                case BuiltInCategory.OST_DuctCurves: return ElementTypeGroup.DuctType;
                case BuiltInCategory.OST_Conduit: return ElementTypeGroup.ConduitType;
                case BuiltInCategory.OST_CableTray: return ElementTypeGroup.CableTrayType;
                case BuiltInCategory.OST_FlexPipeCurves: return ElementTypeGroup.FlexPipeType;
                case BuiltInCategory.OST_FlexDuctCurves: return ElementTypeGroup.FlexDuctType;
                case BuiltInCategory.OST_Viewports: return ElementTypeGroup.ViewportType;
                default: return null;
            }
        }
