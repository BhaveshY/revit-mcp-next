        /// <summary>id | exact name | "active" (the active plan's level).</summary>
        public static Level Level(Document doc, string value, string param = "level", UIDocument uidoc = null)
        {
            string text = (value ?? string.Empty).Trim();
            if (text.Equals("active", StringComparison.OrdinalIgnoreCase))
            {
                View view = uidoc?.ActiveView ?? SafeActiveView(doc);
                Level level = view?.GenLevel;
                if (level != null) return level;
                throw new OpException(ErrorCodes.NotFound, "The active view has no level.", Details(param, "level", value, LevelNames(doc)));
            }
            List<Level> levels = new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.Level)).Cast<Level>().ToList();
            Level byId = ById<Level>(doc, text);
            if (byId != null) return byId;
            return Single(levels, l => l.Name, text, param, "level");
        }

        /// <summary>The level at or below z (feet), else the lowest one; null when the document has no levels.</summary>
        public static Level NearestLevel(Document doc, double zFeet)
        {
            List<Level> levels = new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.Level)).Cast<Level>()
                .OrderBy(l => l.ProjectElevation).ToList();
            if (levels.Count == 0) return null;
            Level below = levels.LastOrDefault(l => l.ProjectElevation <= zFeet + 1e-6);
            return below ?? levels[0];
        }

        /// <summary>The next level above <paramref name="level"/> (null when it is the highest).</summary>
        public static Level LevelAbove(Document doc, Level level)
        {
            return new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.Level)).Cast<Level>()
                .Where(l => l.ProjectElevation > level.ProjectElevation + 1e-6)
                .OrderBy(l => l.ProjectElevation)
                .FirstOrDefault();
        }

