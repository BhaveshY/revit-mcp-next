        /// <summary>"active" | id | exact view name (non-templates first) | sheet number.</summary>
        public static View View(Document doc, string value, string param = "view", UIDocument uidoc = null)
        {
            string text = (value ?? string.Empty).Trim();
            if (text.Length == 0 || text.Equals("active", StringComparison.OrdinalIgnoreCase))
            {
                View active = uidoc?.ActiveView ?? SafeActiveView(doc);
                if (active != null) return active;
                throw new OpException(ErrorCodes.NotFound, "The document has no active view.", Details(param, "view", value, new string[0]));
            }
            View byId = ById<View>(doc, text);
            if (byId != null) return byId;

            List<View> views = new FilteredElementCollector(doc).OfClass(typeof(Autodesk.Revit.DB.View)).Cast<View>().ToList();
            List<View> named = views.Where(v => Eq(v.Name, text)).ToList();
            List<View> nonTemplates = named.Where(v => !v.IsTemplate).ToList();
            if (nonTemplates.Count == 1) return nonTemplates[0];
            if (nonTemplates.Count == 0 && named.Count == 1) return named[0];

            List<ViewSheet> sheets = views.OfType<ViewSheet>().Where(s => Eq(s.SheetNumber, text) || Eq(s.SheetNumber + " - " + s.Name, text)).ToList();
            if (sheets.Count == 1) return sheets[0];

            if (nonTemplates.Count > 1)
            {
                throw OpException.Ambiguous(param, "view", value, nonTemplates.Select(v => v.Name + " (" + v.ViewType + ", id " + v.Id.Value.ToString(CultureInfo.InvariantCulture) + ")"));
            }
            throw OpException.NotFound(param, "view", value, Closest(text, views.Where(v => !v.IsTemplate).Select(v => v.Name)));
        }

        /// <summary>id | sheet number | sheet name | "A101 - Name".</summary>
        public static ViewSheet Sheet(Document doc, string value, string param = "sheet")
        {
            string text = (value ?? string.Empty).Trim();
            ViewSheet byId = ById<ViewSheet>(doc, text);
            if (byId != null) return byId;
            List<ViewSheet> sheets = new FilteredElementCollector(doc).OfClass(typeof(ViewSheet)).Cast<ViewSheet>().ToList();
            ViewSheet byNumber = sheets.FirstOrDefault(s => Eq(s.SheetNumber, text) || Eq(s.SheetNumber + " - " + s.Name, text));
            if (byNumber != null) return byNumber;
            return Single(sheets, s => s.Name, text, param, "sheet", s => s.SheetNumber + " - " + s.Name);
        }

